//! DRM (ETSI ES 201 980) OFDM tables: robustness modes, carrier ranges, FAC cell positions,
//! frequency / time reference pilots and the scattered (gain reference) pilot rules.
//! From the Dream receiver (tables/TableCarMap.cpp, GPL-2.0-or-later).

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RobMode {
    A,
    B,
    C,
    D,
}

pub const ALL_MODES: [RobMode; 4] = [RobMode::A, RobMode::B, RobMode::C, RobMode::D];
pub const FRAMES_PER_SUPERFRAME: usize = 3;
pub const FAC_CELLS: usize = 65;

pub struct ModeParams {
    /// Useful part length at 48 kHz (samples)
    pub n48: usize,
    /// Guard interval / useful part = num / den
    pub tg_num: usize,
    pub tg_den: usize,
    pub sym_per_frame: usize,
    pub fac: &'static [(u8, i16)],
    pub freq_pilots: [(i16, u16); 3],
    pub time_pilots: &'static [(i16, u16)],
    /// Scattered pilots: k = ceil(fi/2) + fi * (s mod ti) + fi * ti * p
    pub scat_freq_int: i32,
    pub scat_time_int: i32,
    /// x, y, k0 of the phase formula
    pub scat_const: [i32; 3],
    pub scat_cols: usize,
    pub scat_w: &'static [i32],
    pub scat_z: &'static [i32],
    pub scat_q: i32,
    /// Boosted scattered pilots per spectrum occupancy (SO 0..5)
    pub boosted: [[i32; 4]; 6],
    /// Carrier range per spectrum occupancy (SO 0..5); (0, 0) = not defined for this mode
    pub kmin: [i32; 6],
    pub kmax: [i32; 6],
    /// Number of first symbols of the superframe carrying the SDC
    pub sdc_symbols: usize,
}

