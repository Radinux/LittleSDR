impl ModeParams {
    /// Useful part and guard at `rate` (samples)
    pub fn tu(&self, rate: f64) -> usize {
        (self.n48 as f64 * rate / 48_000.0).round() as usize
    }
    pub fn tg(&self, rate: f64) -> usize {
        self.tu(rate) * self.tg_num / self.tg_den
    }
}
